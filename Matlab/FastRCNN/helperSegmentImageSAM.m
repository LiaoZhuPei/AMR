function [L,scores] = helperSegmentImageSAM(X,Nvargs)
% HELPERSEGMENTIMAGESAM - Segment image using the Segment Anything Model (SAM).
%   [L, SCORES] = HELPERSEGMENTIMAGESAM(X, NVARGS) segments the input image
%   X using SAM, generating a label matrix (L) and segmentation scores (SCORES).
%
%   Inputs:
%       X       - Input image to segment (2D matrix).
%       NVARGS  - Name-Value pairs for optional parameters:
%                   MinObjectArea         - Minimum object area (default: 0).
%                   MaxObjectArea         - Maximum object area (default: image size / 8).
%                   PointGridSize         - Size of the SAM point grid (default: [256, 32]).
%
%   Outputs:
%       L       - Label matrix indicating segmented regions.
%       SCORES  - Scores associated with the segmented regions.
%
%   Example:
%       [L, scores] = helperSegmentImageSAM(image, ...
%                           MinObjectArea=50, ...
%                           MaxObjectArea=5000, ...
%                           PointGridSize=[128, 64]);
%
% This function is only intended to support examples in the Signal
% Processing and Wavelet Toolboxes. It may change or be removed in a future
% release.

arguments
    X
    Nvargs.MinObjectArea = 0;
    Nvargs.MaxObjectArea = [];
    Nvargs.PointGridSize = [256 32];
end

thres = prctile(X(:),60);
mask = X>thres;
mask = medfilt2(mask,[3,3]);
mask = medfilt2(mask,[7,7]);

Xmin = min(X(:));
Xmax = max(X(:));
if isequal(Xmax,Xmin)
    X = 0*X;
else
    X = (X - Xmin) ./ (Xmax - Xmin);
end

% SAM expects image data to be in the range [0-255].
samImage = 255*rescale(X);
if isempty(Nvargs.MaxObjectArea)
    Nvargs.MaxObjectArea = size(X,1)*size(X,2)/8;
end

[cc,scores] = imsegsam(samImage, ...
    MinObjectArea=Nvargs.MinObjectArea , ...
    MaxObjectArea=Nvargs.MaxObjectArea, ...
    PointGridMask = mask, ...
    PointGridSize=[64 32], ...
    ScoreThreshold=0.5, ...
    ExecutionEnvironment="auto", ...
    SelectStrongestThreshold=0.3, ...
    PointBatchSize=128);
L = labelmatrix(cc);
L = refineBorders(L);
end
% 
function refinedL = refineBorders(L)
% Helper function that refines the label matrix generated by SAM Automatic
% Segmentation

% Get unique labels in input. Ignore the background.
labels = unique(L);
labels = labels(labels ~= 0);

% Initialize the output
refinedL = zeros(size(L), "like", L);

% Create a structuring element for morphological operations
se = strel("disk", 2);

for cnt = 1:numel(labels)
    currLabel = labels(cnt);

    mask = L == currLabel;

    openedMask = imopen(mask, se);

    refinedL(openedMask) = currLabel;
end
end
